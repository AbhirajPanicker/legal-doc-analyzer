/**
 * Utility for exporting legal reports to Markdown files and triggering Print/PDF.
 */

function downloadFile(filename, content, mimeType = 'text/markdown;charset=utf-8;') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Trigger print dialog with temporary document title so default PDF filename matches the report.
 */
export function printReport(title) {
  const originalTitle = document.title;
  document.title = title || 'Legal_Report';
  window.print();
  setTimeout(() => {
    document.title = originalTitle;
  }, 1000);
}

/**
 * Export Executive Summary as a clean Markdown report (.md)
 */
export function exportSummaryMarkdown(docName, summary) {
  const cleanName = (docName || 'Document').replace(/\.pdf$/i, '');
  const timestamp = new Date().toLocaleString();

  let md = `# Executive Summary Report — ${cleanName}\n\n`;
  md += `> **Generated by:** LexAnalyzer Legal AI\n`;
  md += `> **Date:** ${timestamp}\n`;
  md += `> **Analysis Mode:** ${summary.llm_used ? 'AI-Powered (LLM)' : 'Deterministic Legal Rule Engine (Offline)'}\n\n`;
  md += `---\n\n`;

  // One line summary
  if (summary.one_line_summary) {
    md += `## 📌 Overview\n\n`;
    md += `> ${summary.one_line_summary}\n\n`;
  }

  // Key Metadata
  md += `## 📋 Document Profile\n\n`;
  md += `| Attribute | Details |\n`;
  md += `| :--- | :--- |\n`;
  md += `| **Document Type** | ${summary.document_type || 'Legal Agreement'} |\n`;
  md += `| **Governing Law** | ${summary.governing_law || 'Not specified'} |\n`;
  md += `| **Analysis Engine** | ${summary.llm_used ? 'Cloud LLM' : 'Offline Engine'} |\n\n`;

  // Parties
  md += `## 👥 Parties Involved\n\n`;
  if (summary.parties && summary.parties.length > 0) {
    summary.parties.forEach((p, i) => {
      md += `* **${p.role || `Party ${i + 1}`}**: ${p.name}\n`;
    });
  } else {
    md += `*No named parties explicitly identified.*\n`;
  }
  md += `\n`;

  // Key Dates
  md += `## 📅 Key Dates & Milestones\n\n`;
  if (summary.key_dates && summary.key_dates.length > 0) {
    summary.key_dates.forEach(d => {
      md += `* **${d.label}**: ${d.date}\n`;
    });
  } else {
    md += `*No key milestone dates identified.*\n`;
  }
  md += `\n`;

  // Financial Terms
  md += `## 💰 Financial Terms & Considerations\n\n`;
  if (summary.financial_terms && summary.financial_terms.length > 0) {
    summary.financial_terms.forEach(f => {
      md += `* **${f.label}**: ${f.value}\n`;
    });
  } else {
    md += `*No explicit financial covenants or fees specified.*\n`;
  }
  md += `\n`;

  // Key Obligations
  md += `## 📝 Core Contractual Obligations\n\n`;
  if (summary.obligations && summary.obligations.length > 0) {
    summary.obligations.forEach((o, i) => {
      md += `${i + 1}. ${o}\n`;
    });
  } else {
    md += `*Standard contractual terms apply.*\n`;
  }
  md += `\n`;

  // Termination
  md += `## 🚪 Termination & Default Provisions\n\n`;
  md += `${summary.termination_conditions || 'Standard statutory termination rights apply or conditions not specifically detailed.'}\n\n`;

  // Risk Flags
  md += `## ⚠️ Identified Legal Risks & Covenants\n\n`;
  if (summary.risk_flags && summary.risk_flags.length > 0) {
    summary.risk_flags.forEach(r => {
      const severityEmoji = r.severity === 'high' ? '🔴 HIGH' : r.severity === 'medium' ? '🟡 MEDIUM' : '🟢 LOW';
      md += `* [${severityEmoji}] ${r.description}\n`;
    });
  } else {
    md += `*No elevated risk covenants flagged.*\n`;
  }
  md += `\n---\n`;
  md += `*Disclaimer: This report was automatically generated for informational purposes. It does not constitute formal legal counsel.*\n`;

  downloadFile(`Legal_Summary_${cleanName.replace(/[^a-zA-Z0-9_-]/g, '_')}.md`, md);
}

/**
 * Export Clause & Risk Analysis as a Markdown report (.md)
 */
export function exportClauseMarkdown(docName, analysis) {
  const cleanName = (docName || 'Document').replace(/\.pdf$/i, '');
  const timestamp = new Date().toLocaleString();

  let md = `# Legal Clause & Risk Audit Report — ${cleanName}\n\n`;
  md += `> **Generated by:** LexAnalyzer Legal AI\n`;
  md += `> **Date:** ${timestamp}\n`;
  md += `> **Overall Assessment:** ${(analysis.overall_risk || 'LOW').toUpperCase()} RISK\n`;
  md += `> **Clauses Audited:** ${analysis.total_clauses_found || 0} Found | ${analysis.total_clauses_missing || 0} Missing Protections\n\n`;
  md += `---\n\n`;

  // Executive Risk Note
  if (analysis.analysis_note) {
    md += `## 🛡️ Risk Assessment Overview\n\n`;
    md += `> **Status:** ${(analysis.overall_risk || 'LOW').toUpperCase()} RISK\n`;
    md += `> ${analysis.analysis_note}\n\n`;
  }

  // Risk Distribution
  md += `## 📊 Risk Breakdown\n\n`;
  md += `* 🔴 **High Risk Items:** ${analysis.high_risk_count || 0}\n`;
  md += `* 🟡 **Medium Risk Items:** ${analysis.medium_risk_count || 0}\n`;
  md += `* 🟢 **Low Risk Items:** ${analysis.low_risk_count || 0}\n\n`;

  // Detected clauses
  md += `## 🔍 Detected Contract Clauses\n\n`;
  if (analysis.detected_clauses && analysis.detected_clauses.length > 0) {
    analysis.detected_clauses.forEach((c, idx) => {
      const badge = (c.risk || 'low').toUpperCase();
      md += `### ${idx + 1}. ${c.icon || '📌'} ${c.clause_name} — [${badge} RISK]\n\n`;
      md += `* **Assessment:** ${c.description}\n`;
      if (c.text_excerpt) {
        md += `* **Contract Language:**\n  > "${c.text_excerpt.trim()}"\n`;
      }
      if (c.standard_note) {
        md += `* **Standard Recommendation:** ${c.standard_note}\n`;
      }
      md += `\n`;
    });
  }

  // Missing clauses
  md += `## 🚫 Missing Standard Protections\n\n`;
  if (analysis.missing_clauses && analysis.missing_clauses.length > 0) {
    analysis.missing_clauses.forEach((c, idx) => {
      const badge = (c.risk || 'medium').toUpperCase();
      md += `### ${idx + 1}. ⚠️ Missing: ${c.clause_name} — [${badge} RISK]\n\n`;
      md += `* **Risk Implication:** ${c.description}\n`;
      if (c.standard_note) {
        md += `* **Recommended Clause:** ${c.standard_note}\n`;
      }
      md += `\n`;
    });
  } else {
    md += `*All core standard protective clauses were detected in this agreement.*\n\n`;
  }

  md += `---\n`;
  md += `*Disclaimer: This report was automatically generated for informational purposes. It does not constitute formal legal counsel.*\n`;

  downloadFile(`Clause_Audit_${cleanName.replace(/[^a-zA-Z0-9_-]/g, '_')}.md`, md);
}

/**
 * Export Contract Blind-Spot Audit as a Markdown report (.md)
 */
export function exportBlindSpotMarkdown(docName, analysis) {
  const cleanName = (docName || 'Document').replace(/\.pdf$/i, '');
  const timestamp = new Date().toLocaleString();

  let md = `# 🔍 Contract Blind-Spot Audit: ${cleanName}\n\n`;
  md += `*Generated: ${timestamp} via LexAnalyzer Legal AI*\n\n`;
  md += `---\n\n`;

  // Executive Takeaway
  md += `## 📋 Executive Takeaway\n\n`;
  md += `> ${analysis.executive_takeaway || 'Comprehensive blind-spot analysis completed.'}\n\n`;

  // Summary Metrics
  md += `## 📊 Risk & Category Breakdown\n\n`;
  md += `| Metric | Count |\n`;
  md += `|---|---|\n`;
  md += `| **Total Blind Spots Flagged** | **${analysis.total_findings || 0}** |\n`;
  md += `| 🔴 High Severity | ${analysis.high_severity_count || 0} |\n`;
  md += `| 🟡 Medium Severity | ${analysis.medium_severity_count || 0} |\n`;
  md += `| 🟡 Low Severity | ${analysis.low_severity_count || 0} |\n\n`;

  if (analysis.categories_summary && Object.keys(analysis.categories_summary).length > 0) {
    md += `### Category Distribution\n\n`;
    Object.entries(analysis.categories_summary).forEach(([cat, count]) => {
      md += `- **${cat}:** ${count}\n`;
    });
    md += `\n`;
  }

  // Findings
  md += `## 📑 Detailed Findings & Legal Review Questions\n\n`;
  if (analysis.findings && analysis.findings.length > 0) {
    analysis.findings.forEach((f, idx) => {
      const pageStr = f.page_number ? `Page ${f.page_number}` : 'Agreement-Wide / General Omission';
      md += `### ${idx + 1}. [${f.severity.toUpperCase()}] ${f.title}\n\n`;
      md += `- **Category:** \`${f.category}\` | **Gap Type:** ${f.gap_type}\n`;
      md += `- **Location / Scope:** ${pageStr}\n`;
      md += `- **Explanation:** ${f.explanation}\n`;
      if (f.evidence) {
        md += `- **Supporting Evidence / Clause:**\n  > "${f.evidence.trim()}"\n`;
      }
      md += `- **❓ Question for Legal Counsel Review:**\n  > **${f.human_review_question}**\n\n`;
    });
  } else {
    md += `*No contractual blind spots or ambiguities detected in this document.*\n\n`;
  }

  md += `---\n`;
  md += `*Disclaimer: ${analysis.disclaimer || 'All findings are preliminary automated observations and do not constitute formal legal counsel. Human legal review by qualified counsel is required.'}*\n`;

  downloadFile(`Blind_Spot_Audit_${cleanName.replace(/[^a-zA-Z0-9_-]/g, '_')}.md`, md);
}

